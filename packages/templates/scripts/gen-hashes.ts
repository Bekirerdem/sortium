// Regenerates src/codehashes.ts from the pure resolver sources. Run after editing any file in src/resolve/.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { keccak256, toHex } from "viem";

const dir = join(import.meta.dir, "..", "src", "resolve");
const entries = readdirSync(dir)
  .filter((f) => f.endsWith(".ts"))
  .sort()
  .map((f) => `  "resolve/${f}": "${keccak256(toHex(readFileSync(join(dir, f), "utf8")))}",`);
writeFileSync(
  join(import.meta.dir, "..", "src", "codehashes.ts"),
  `// Generated by scripts/gen-hashes.ts — keccak256 of each pure resolver source file.\nexport const CODE_HASHES: Record<string, \`0x\${string}\`> = {\n${entries.join("\n")}\n};\n`,
);
console.log(entries.join("\n"));
